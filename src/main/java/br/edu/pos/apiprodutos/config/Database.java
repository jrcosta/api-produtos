
package br.edu.pos.apiprodutos.config;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;
import java.sql.ResultSet;

public class Database {

    private static final String URL =
            "jdbc:h2:file:./dados/produtos;AUTO_SERVER=TRUE";

    private static final String USUARIO = "sa";
    private static final String SENHA = "";

    public static Connection conectar() throws SQLException {

        return DriverManager.getConnection(
                URL,
                USUARIO,
                SENHA
        );
    }

    public static void inicializar() {

        String sql = """
                CREATE TABLE IF NOT EXISTS produtos (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    nome VARCHAR(150) NOT NULL,
                    preco DOUBLE PRECISION NOT NULL,
                    quantidade_estoque INT DEFAULT 0 NOT NULL
                )
                """;

        try (
                Connection conexao = conectar();
                Statement comando = conexao.createStatement()
        ) {

            comando.execute(sql);

            // Adicionar coluna se não existir (para compatibilidade com banco existente)
            adicionarColunaEstoqueSeNaoExistir(conexao);

            System.out.println("Banco de dados inicializado!");

        } catch (SQLException erro) {

            throw new RuntimeException(
                    "Erro ao inicializar banco de dados",
                    erro
            );
        }
    }

    private static void adicionarColunaEstoqueSeNaoExistir(Connection conexao) {
        String sqlVerificar = """
                SELECT COUNT(*) FROM information_schema.columns 
                WHERE table_name = 'PRODUTOS' AND column_name = 'QUANTIDADE_ESTOQUE'
                """;
        
        String sqlAlterar = "ALTER TABLE produtos ADD COLUMN quantidade_estoque INT DEFAULT 0 NOT NULL";

        try (
                Statement comando = conexao.createStatement();
                ResultSet rs = comando.executeQuery(sqlVerificar)
        ) {
            if (rs.next() && rs.getInt(1) == 0) {
                try (Statement cmdAlterar = conexao.createStatement()) {
                    cmdAlterar.execute(sqlAlterar);
                    System.out.println("Coluna quantidade_estoque adicionada ao banco de dados!");
                }
            }
        } catch (SQLException erro) {
            // Coluna pode já existir, continuar silenciosamente
        }
    }
}
